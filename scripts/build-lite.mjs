import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const dist=path.join(root,'dist-lite');
const mode=process.argv[2]||'emulator';
if(!['emulator','test','spark','spark-emulator'].includes(mode))throw Error('Unsupported HUB build');
await fs.rm(dist,{recursive:true,force:true});
await fs.cp(path.join(root,'src/lite'),dist,{recursive:true});
await fs.cp(path.join(root,'src/assets'),path.join(dist,'assets'),{recursive:true});
for(const name of ['firebase-app-compat.js','firebase-auth-compat.js'])await fs.copyFile(path.join(root,'node_modules/firebase',name),path.join(dist,name));
await fs.writeFile(path.join(dist,'build-info.json'),JSON.stringify({code:'HFI-HB',version:mode.startsWith('spark')?'3.0 LITE C03 Spark':'3.0 LITE C02',mode,projectId:mode==='spark-emulator'?'demo-hub-spark':mode==='emulator'?'demo-hub-lite':'hub-ptn-test'}));
if(mode.startsWith('spark'))await import('./spark-rules.mjs');
console.log('HUB-HFI V3.0 LITE · '+mode);
